import { expect, test } from '@playwright/test';
import { mkdir, readFile } from 'node:fs/promises';
import { resolve } from 'node:path';

test('switching animation sets while the authored stage starts tears down without page errors', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', (error) => errors.push(error.message));
  await page.addInitScript(() => localStorage.clear());
  await page.goto('/#builder');
  await page.getByLabel('Animation set', { exact: true }).selectOption('coqfight-v1');
  await expect(page.getByRole('status')).toContainText('41 official clips');
  await page.getByLabel('Official species', { exact: true }).selectOption('roostr');
  await expect(page.getByLabel('Official traits', { exact: true }).locator('option')).toHaveCount(224);
  await expect(page.getByRole('status')).toContainText('41 official clips');
  await expect(page.locator('main canvas')).toHaveCount(1);
  expect(errors).toEqual([]);
});

test('official catalog renders both species and controlled clips with independent recipe persistence', async ({ page }) => {
  await page.addInitScript(() => { if (!sessionStorage.getItem('coqfight-test-started')) { localStorage.clear(); sessionStorage.setItem('coqfight-test-started', '1'); } });
  await page.goto('/#builder');
  await page.getByLabel('Animation set', { exact: true }).selectOption('coqfight-v1');
  const status = page.getByRole('status');
  await expect(status).toContainText('41 official clips');
  await expect(page.getByLabel('Official animation', { exact: true }).locator('option')).toHaveCount(41);
  await expect(page.getByLabel('Official body', { exact: true }).locator('option')).toHaveCount(21);
  await expect(page.getByLabel('Official traits', { exact: true }).locator('option')).toHaveCount(174);
  const review = resolve('.release/review'); await mkdir(review, { recursive: true });
  const screenshot = async (name: string) => page.locator('.coqfight-stage').screenshot({ path: resolve(review, `${test.info().project.name}-${name}.png`) });
  await screenshot('chikn-idle');
  await page.getByLabel('Show official bounds', { exact: true }).check();
  await page.getByLabel('Official animation', { exact: true }).selectOption('Headbutt');
  await page.getByRole('button', { name: 'Pause', exact: true }).click();
  await page.getByLabel('Preview approach motion', { exact: true }).check();
  await page.getByLabel('Official animation time', { exact: true }).evaluate((element) => { (element as HTMLInputElement).value = '912'; element.dispatchEvent(new Event('input', { bubbles: true })); });
  await screenshot('chikn-headbutt-bounds');
  await page.getByRole('button', { name: 'Play', exact: true }).click();
  await page.getByLabel('Official animation', { exact: true }).selectOption('RifleShot');
  await page.getByRole('button', { name: 'Pause', exact: true }).click();
  await page.getByLabel('Official animation time', { exact: true }).press('Home');
  for (let i = 0; i < 4; i += 1) await page.getByLabel('Official animation time', { exact: true }).press('PageUp');
  await screenshot('chikn-rifle-shot');
  await page.getByRole('button', { name: 'Play', exact: true }).click();
  await page.getByLabel('Official animation', { exact: true }).selectOption('Death');
  await expect(page.getByLabel('Loop official animation', { exact: true })).not.toBeChecked();
  await page.getByRole('button', { name: 'Pause', exact: true }).click();
  await page.getByLabel('Official animation time', { exact: true }).press('Home');
  await page.getByLabel('Official animation time', { exact: true }).press('PageUp');
  await screenshot('chikn-death-bounds');
  await page.getByLabel('Official animation time', { exact: true }).press('End');
  await page.getByRole('button', { name: 'Replay', exact: true }).click();
  await page.getByLabel('Official species', { exact: true }).selectOption('roostr');
  await expect(page.getByLabel('Official traits', { exact: true }).locator('option')).toHaveCount(224);
  await expect(status).toContainText('41 official clips');
  await page.getByLabel('Official traits', { exact: true }).selectOption(['trait/roostr_pilothat', 'trait/roostr_formalvest', 'trait/roostr_sword']);
  await expect(status).toContainText('41 official clips');
  await screenshot('roostr-traits');
  await page.getByLabel('Official animation', { exact: true }).selectOption('Walk');
  await expect(page.getByLabel('Loop official animation', { exact: true })).toBeChecked();
  await page.getByLabel('Mirror official character', { exact: true }).check();
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export official recipe', exact: true }).click();
  const downloadPath = await (await download).path();
  const recipe = JSON.parse(await readFile(downloadPath!, 'utf8'));
  expect(recipe).toMatchObject({ schema: 'chikn.coqfight-character/v1', setId: 'coqfight-v1', species: 'roostr', animationName: 'Walk', mirrored: true });
  expect(recipe.renderScale).toBeGreaterThan(0);
  await page.reload();
  await expect(page.getByLabel('Official species', { exact: true })).toHaveValue('roostr');
  await expect(status).toContainText('41 official clips');
  const width = await page.locator('main canvas').evaluate((canvas) => canvas.getBoundingClientRect().width);
  expect(width).toBeLessThanOrEqual(page.viewportSize()!.width);
});

test('a failed replacement preserves the displayed recipe for export and retry', async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('chikn.preview-animation-set.v1', 'coqfight-v1'));
  await page.goto('/#rig');
  await expect(page.getByRole('status')).toContainText('41 official clips');
  await page.route('**/coqfight-v1/roostr/rig.json', (route) => route.fulfill({ status: 503, body: 'temporarily unavailable' }));
  await page.getByLabel('Official species', { exact: true }).selectOption('roostr');
  await expect(page.getByRole('status')).toContainText('503');
  await page.getByRole('button', { name: 'Replay', exact: true }).click();
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export official recipe', exact: true }).click();
  const downloadPath = await (await download).path();
  const recipe = JSON.parse(await readFile(downloadPath!, 'utf8'));
  expect(recipe.species).toBe('chikn');
  await page.unroute('**/coqfight-v1/roostr/rig.json');
  await page.getByRole('button', { name: 'Retry', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('41 official clips');
});
